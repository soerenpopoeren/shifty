"""Converts the shifter drawing (Assets/shifter.svg) into SwiftUI paths.

Usage: python3 Tools/svg2swift.py Assets/shifter.svg > Sources/ShifterShapes.swift

Every <g id="..."> with a <path d="..."> becomes one shape. Coordinates are kept in SVG units
and scaled to the target rectangle at runtime, so the drawing stays crisp at any size.
Supported path commands: M L H V C S Q T Z (absolute and relative).
"""
import re, sys, xml.etree.ElementTree as ET

def tokens(d):
    for m in re.finditer(r'[MmLlHhVvCcSsQqTtZz]|-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?', d):
        yield m.group(0)

def parse(d):
    toks = list(tokens(d)); i = 0; cmd = None
    x = y = sx = sy = 0.0; last_ctrl = None; out = []
    def num():
        nonlocal i
        v = float(toks[i]); i += 1; return v
    while i < len(toks):
        if re.match(r'[A-Za-z]', toks[i]):
            cmd = toks[i]; i += 1
            if cmd in 'Zz':
                out.append(('Z',)); x, y = sx, sy; last_ctrl = None; continue
        rel = cmd.islower(); c = cmd.upper()
        ox, oy = (x, y) if rel else (0.0, 0.0)
        if c == 'M':
            x, y = ox + num(), oy + num(); sx, sy = x, y; out.append(('M', x, y))
            cmd = 'l' if rel else 'L'; last_ctrl = None
        elif c == 'L':
            x, y = ox + num(), oy + num(); out.append(('L', x, y)); last_ctrl = None
        elif c == 'H':
            x = ox + num(); out.append(('L', x, y)); last_ctrl = None
        elif c == 'V':
            y = (y if rel else 0.0) + num(); out.append(('L', x, y)); last_ctrl = None
        elif c == 'C':
            x1, y1, x2, y2 = ox + num(), oy + num(), ox + num(), oy + num()
            x, y = ox + num(), oy + num()
            out.append(('C', x1, y1, x2, y2, x, y)); last_ctrl = (x2, y2)
        elif c == 'S':
            x1, y1 = (2 * x - last_ctrl[0], 2 * y - last_ctrl[1]) if last_ctrl else (x, y)
            x2, y2 = ox + num(), oy + num(); x, y = ox + num(), oy + num()
            out.append(('C', x1, y1, x2, y2, x, y)); last_ctrl = (x2, y2)
        elif c == 'Q':
            qx, qy = ox + num(), oy + num(); x, y = ox + num(), oy + num()
            out.append(('Q', qx, qy, x, y)); last_ctrl = (qx, qy)
        elif c == 'T':
            qx, qy = (2 * x - last_ctrl[0], 2 * y - last_ctrl[1]) if last_ctrl else (x, y)
            x, y = ox + num(), oy + num(); out.append(('Q', qx, qy, x, y)); last_ctrl = (qx, qy)
        else:
            raise ValueError('unsupported command ' + cmd)
    return out

def f(v): return ('%.3f' % v).rstrip('0').rstrip('.')

def swift(name, cmds):
    lines = [f'    static func {name}(_ p: (CGFloat, CGFloat) -> CGPoint) -> Path {{', '        var path = Path()']
    for c in cmds:
        if c[0] == 'M': lines.append(f'        path.move(to: p({f(c[1])}, {f(c[2])}))')
        elif c[0] == 'L': lines.append(f'        path.addLine(to: p({f(c[1])}, {f(c[2])}))')
        elif c[0] == 'C': lines.append(f'        path.addCurve(to: p({f(c[5])}, {f(c[6])}), control1: p({f(c[1])}, {f(c[2])}), control2: p({f(c[3])}, {f(c[4])}))')
        elif c[0] == 'Q': lines.append(f'        path.addQuadCurve(to: p({f(c[3])}, {f(c[4])}), control: p({f(c[1])}, {f(c[2])}))')
        elif c[0] == 'Z': lines.append('        path.closeSubpath()')
    lines += ['        return path', '    }']
    return '\n'.join(lines)

def camel(s):
    parts = re.split(r'[-_ ]', s); return parts[0].lower() + ''.join(p.capitalize() for p in parts[1:])

ns = {'svg': 'http://www.w3.org/2000/svg'}
root = ET.parse(sys.argv[1]).getroot()
vb = [float(v) for v in root.get('viewBox').split()]
shapes = []
for g in root.iter('{http://www.w3.org/2000/svg}g'):
    gid = g.get('id')
    paths = g.findall('svg:path', ns)  # direct children only; nested groups get their own shape
    if gid and paths:
        shapes.append((camel(gid), [c for pth in paths for c in parse(pth.get('d'))]))

print('// SPDX-License-Identifier: GPL-3.0-or-later')
print('// Copyright (C) 2026 soerenpopoeren (code and shifter drawing)')
print('// GENERATED by Tools/svg2swift.py from Assets/shifter.svg – do not edit by hand.')
print()
print('import SwiftUI')
print()
print('enum ShifterShapes {')
print(f'    static let viewBox = CGSize(width: {f(vb[2])}, height: {f(vb[3])})')
print()
print('\n\n'.join(swift(n, c) for n, c in shapes))
print('}')
